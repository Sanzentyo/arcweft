//! Semantic argument coordinates shared by checking and executable commands.

use serde::{Deserialize, Serialize};

/// Semantic destination of a presentation argument. The selected schema owns
/// the role independently of a parameter's source label or ordinal.
#[derive(Clone, Copy, Debug, Deserialize, Eq, Hash, Ord, PartialEq, PartialOrd, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum PresentationArgumentRole {
    View,
    Asset,
    Lifetime,
    TargetEntity,
    TargetPublicId,
    LayerPublicId,
    Slot,
    Scope,
    Fade,
    Fit,
    Opacity,
    Id,
    Handle,
    Key,
    Mount,
    Depth,
    Enabled,
    Visible,
    Action,
    Actions,
    X,
    Y,
    Width,
    Height,
    Focus,
    InputCapture,
    Owner,
    Drop,
    AlignmentX,
    AlignmentY,
    PlaybackStart,
    PlaybackPausedAt,
    PlaybackLocalTime,
    PlaybackRate,
    TransformTx,
    TransformTy,
    TransformM11,
    TransformM12,
    TransformM21,
    TransformM22,
    ProxyId,
    ProxyType,
    ProxyRole,
    ProxyLayer,
    ProxyDepth,
    ProxyHitTest,
    Parameter,
    ProxyParameter,
    Look,
    Source,
    Character,
}

impl PresentationArgumentRole {
    pub const fn semantic_tag(self) -> u8 {
        match self {
            Self::View => 0,
            Self::Asset => 1,
            Self::Lifetime => 2,
            Self::TargetEntity => 3,
            Self::TargetPublicId => 4,
            Self::LayerPublicId => 5,
            Self::Slot => 6,
            Self::Scope => 7,
            Self::Fade => 8,
            Self::Fit => 9,
            Self::Opacity => 10,
            Self::Id => 11,
            Self::Handle => 12,
            Self::Key => 13,
            Self::Mount => 14,
            Self::Depth => 15,
            Self::Enabled => 16,
            Self::Visible => 17,
            Self::Action => 18,
            Self::Actions => 19,
            Self::X => 20,
            Self::Y => 21,
            Self::Width => 22,
            Self::Height => 23,
            Self::Focus => 24,
            Self::InputCapture => 25,
            Self::Owner => 26,
            Self::Drop => 27,
            Self::AlignmentX => 28,
            Self::AlignmentY => 29,
            Self::PlaybackStart => 30,
            Self::PlaybackPausedAt => 31,
            Self::PlaybackLocalTime => 32,
            Self::PlaybackRate => 33,
            Self::TransformTx => 34,
            Self::TransformTy => 35,
            Self::TransformM11 => 36,
            Self::TransformM12 => 37,
            Self::TransformM21 => 38,
            Self::TransformM22 => 39,
            Self::ProxyId => 40,
            Self::ProxyType => 41,
            Self::ProxyRole => 42,
            Self::ProxyLayer => 43,
            Self::ProxyDepth => 44,
            Self::ProxyHitTest => 45,
            Self::Parameter => 46,
            Self::ProxyParameter => 47,
            Self::Look => 48,
            Self::Source => 49,
            Self::Character => 50,
        }
    }
}
