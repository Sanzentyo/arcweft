#[test]
fn parses_documented_trait_and_impl_items() {
    let tree = parse_ok(
        r"
pub trait Mappable {
    type Item
    type Mapped<B>
    fn map<B>(self, f: Self::Item -> B) -> Self.Mapped<B>
}

pub trait Ord: Eq {}

pub impl<T> Mappable for Option<T> {
    type Item = T
    type Mapped<B> = Option<B>

    fn map<B>(self, f: T -> B) -> Option<B> {
        match self {
            Some(x) => Some(f(x))
            None => None
        }
    }
}
",
    );

    assert_mappable_trait(&tree.typed_tree().items()[0]);

    let Item::Trait(ord) = &tree.typed_tree().items()[1] else {
        panic!("expected second trait item");
    };
    assert_eq!(
        ord.supertraits()
            .iter()
            .map(|bound| bound.value().canonical_label())
            .collect::<Vec<_>>(),
        ["Eq".to_owned()]
    );

    assert_mappable_impl(&tree.typed_tree().items()[2]);

    let hir = lower_document_to_hir(tree.document(), tree.typed_tree())
        .expect("syntax-only trait/impl items do not block HIR");
    assert!(hir.flows().is_empty());
    assert!(matches!(
        hir.declarations(),
        [
            HirTopLevelDecl::Trait(_),
            HirTopLevelDecl::Trait(_),
            HirTopLevelDecl::Impl(_)
        ]
    ));
}

fn assert_mappable_trait(item: &Item) {
    let Item::Trait(mappable) = item else {
        panic!("expected trait item");
    };
    assert_eq!(mappable.visibility(), Some(Visibility::Public));
    assert_eq!(mappable.name(), "Mappable");
    assert_eq!(mappable.members().len(), 3);
    assert!(matches!(
        &mappable.members()[0],
        TraitMember::AssociatedType { name, params, value: None }
            if name == "Item" && params.is_empty()
    ));
    assert!(matches!(
        &mappable.members()[1],
        TraitMember::AssociatedType { name, params, value: None }
            if name == "Mapped" && params == &["B".to_owned()]
    ));
    assert!(matches!(
        &mappable.members()[2],
        TraitMember::Function { signature, .. }
            if signature.name() == "map"
                && signature
                    .param_groups()
                    .first()
                    .and_then(|group| group.params().first())
                    .is_some_and(|param| ident_pattern(param.pattern(), "self"))
    ));
}

fn assert_mappable_impl(item: &Item) {
    let Item::Impl(impl_item) = item else {
        panic!("expected impl item");
    };
    assert_eq!(impl_item.visibility(), Some(Visibility::Public));
    assert_eq!(
        impl_item
            .generics()
            .iter()
            .filter_map(GenericParam::as_type)
            .map(arcweft_lang_syntax::ast::module_path::ModuleSegment::as_str)
            .collect::<Vec<_>>(),
        ["T"]
    );
    assert_eq!(
        impl_item.trait_ref().map(|ty| ty.value().canonical_label()),
        Some("Mappable".to_owned())
    );
    assert_eq!(impl_item.target().value().canonical_label(), "Option<T>");
    assert_eq!(impl_item.members().len(), 3);
    assert!(matches!(
        &impl_item.members()[0],
        ImplMember::AssociatedType { name, params, value }
            if name == "Item" && params.is_empty() && matches!(value.value(), TypeRef::Path(path) if crate::types::direct_type_name(path) == Some("T"))
    ));
    assert!(matches!(
        &impl_item.members()[1],
        ImplMember::AssociatedType { name, params, value }
            if name == "Mapped"
                && params == &["B".to_owned()]
                && matches!(value.value(), TypeRef::Generic { base, args } if crate::types::direct_type_name(base) == Some("Option") && args.len() == 1)
    ));
    assert!(matches!(
        &impl_item.members()[2],
        ImplMember::Function {
            signature,
            body,
            body_statements,
            body_value,
            ..
        }
            if signature.name() == "map"
                && signature
                    .param_groups()
                    .first()
                    .and_then(|group| group.params().first())
                    .is_some_and(|param| ident_pattern(param.pattern(), "self"))
                && body.contains("match self")
                && body_statements.is_empty()
                && matches!(
                    body_value.as_deref().map(AuthoredExpr::expr),
                    Some(Expr::Match { .. })
                )
    ));
    assert!(impl_item.body().contains("Some(x)"));
}

