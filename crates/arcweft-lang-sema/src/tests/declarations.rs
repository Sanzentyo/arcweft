#[test]
fn parses_verified_and_trusted_proofs_as_one_structured_declaration_family() {
    let tree = parse_ok(
        r#"
proof line_summary_to_flow {
    requires summary.lifetime >= 'line
    ensures summary.lifetime >= 'flow
    check no_lifetime_below(LineSummary, 'flow)
}

#[verify.trusted(reason = "resource manifest hashes are generated by signed build tooling")]
proof resource_manifest_hashes {
    check signed_manifest_hashes()
}
"#,
    );

    let Item::Proof(proof) = &tree.typed_tree().items()[0] else {
        panic!("expected proof item");
    };
    assert_eq!(proof.id().body(), "proof.line_summary_to_flow");
    assert!(proof.body().contains("check no_lifetime_below"));
    assert!(matches!(
        proof.clauses(),
        [
            ProofClause::Requires { .. },
            ProofClause::Ensures { lifetime_targets, .. },
            ProofClause::Check { .. },
        ] if lifetime_targets.iter().any(|target| target == "'flow")
    ));

    assert!(matches!(proof.trust(), ProofTrust::Verified));

    let Item::Proof(trusted) = &tree.typed_tree().items()[1] else {
        panic!("expected trusted proof item");
    };
    assert_eq!(trusted.id().body(), "proof.resource_manifest_hashes");
    assert!(matches!(
        trusted.trust(),
        ProofTrust::Trusted { reason, .. }
            if reason == "resource manifest hashes are generated by signed build tooling"
    ));

    let hir = lower_document_to_hir(tree.document(), tree.typed_tree())
        .expect("proof metadata lowers as declarations");
    assert!(matches!(
        &hir.declarations()[0],
        HirTopLevelDecl::Proof(item) if item.id().body() == "proof.line_summary_to_flow"
    ));
    assert!(matches!(
        &hir.declarations()[1],
        HirTopLevelDecl::Proof(item)
            if item.id().body() == "proof.resource_manifest_hashes"
                && matches!(item.trust(), ProofTrust::Trusted { .. })
    ));
}

